import { execSync } from "node:child_process";
import fs from 'fs/promises';
import path from 'path';


async function getLatestMigration() {
  const dir = path.resolve('prisma/migrations');
  const folders = await fs.readdir(dir);

  // sort by folder name (timestamp prefix guarantees order)
  const sorted = folders.sort().reverse().filter(name => /^\d/.test(name));
  const latest = sorted[0];

  return path.join(dir, latest, 'migration.sql');
}

async function replaceSerial() {
  const filePath = await getLatestMigration();
  try {
    const sql = await fs.readFile(filePath, 'utf8');

    const replaced = sql.replace(
      /\bSERIAL\b/gi,
      'INTEGER GENERATED BY DEFAULT AS IDENTITY'
    );

    await fs.writeFile(filePath, replaced, 'utf8');
    console.log(`Changes applied to migration file: ${filePath}`);
  } catch (err) {
    console.error('Error:', err.message);
  }
}

const name = process.argv[2];

if (!name) {
  console.error("Error: Migration name required.\nUsage: npm run migrate <name>");
  process.exit(1);
}

execSync(`npx prisma migrate dev --name "${name}" --create-only`, { stdio: "inherit" });
await replaceSerial();
execSync(`npx prisma migrate deploy`, { stdio: "inherit" });
execSync(`npx prisma generate`, { stdio: "inherit" });
